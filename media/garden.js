  function plantStage(plant) {
    if (state.mode === 'blooming') return 4;
    const elapsed = Date.now() - plant.plantedAt + (plant.growthBonusMs || 0);
    return Math.max(0, Math.min(4, Math.floor((elapsed / config.lifecycleMs) * 4)));
  }

  function gardenStage() {
    const list = livePlants();
    if (!list.length) return 4;
    let lowest = 4;
    list.forEach(p => { lowest = Math.min(lowest, plantStage(p)); });
    return lowest;
  }

  function groundShadow(x, y, width, depth) {
    const half = Math.max(3, Math.round(width * 0.34));
    ctx.fillStyle = depth === 2 ? 'rgba(38,26,16,0.14)' : 'rgba(38,26,16,0.22)';
    ctx.fillRect(Math.round(x - half), Math.round(y) - 2, half * 2, 2);
    ctx.fillRect(Math.round(x - half) + 2, Math.round(y) - 3, half * 2 - 4, 1);
  }

  function drawPlants(time) {
    const table = slotTable();
    const drawable = livePlants()
      .filter(p => p.slot < table.length)
      .map(p => ({ plant: p, slot: table[p.slot] }))
      .sort((a, b) => a.slot.y - b.slot.y);
    drawable.forEach(({ plant, slot }, index) => {
      const stage = plantStage(plant);
      const sprite = SPRITES[plant.species].stages[STAGE_KEYS[stage]];
      if (!sprite) return;
      const sway = reducedMotion || stage < 3 ? 0 : Math.round(Math.sin(time / 900 + index * 1.7));
      const width = Math.max.apply(null, sprite.map(row => row.length));
      groundShadow(slot.x, slot.y, width, slot.depth);
      drawSprite(sprite, slot.x, slot.y, slot.depth, sway, slot.flip);
    });
  }

