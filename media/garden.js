  function background(biomeId, wet) {
    const theme = THEMES[biomeId] || THEMES.meadow;
    const key = biomeId + (wet ? ':wet' : ':dry');
    if (bgCache[key]) return bgCache[key];
    const layer = document.createElement('canvas');
    layer.width = CW;
    layer.height = CH;
    const g = layer.getContext('2d');
    g.imageSmoothingEnabled = false;
    const f = (x, y, w, h, color) => { g.fillStyle = color; g.fillRect(x, y, w, h); };

    // Sky, banded and dithered so the gradient stays inside the palette.
    const step = HORIZON / 5;
    const bands = [0, step, step * 2, step * 3, step * 4, HORIZON + 6].map(Math.round);
    for (let i = 0; i < theme.sky.length; i++) f(0, bands[i], CW, bands[i + 1] - bands[i], theme.sky[i]);
    for (let i = 1; i < theme.sky.length; i++) {
      for (let y = bands[i] - 3; y < bands[i] + 1; y++) {
        for (let x = 0; x < CW; x++) if ((x + y) % 2 === 0) f(x, y, 1, 1, theme.sky[i]);
      }
    }

    // Sun: a clean two-tone disc with one soft ring of glow.
    const sunX = CW - 44, sunY = 28;
    for (let dy = -14; dy <= 14; dy++) {
      for (let dx = -14; dx <= 14; dx++) {
        const d = Math.sqrt(dx * dx + dy * dy);
        let color = null;
        if (d <= 8.4) color = (dx - dy) > 3 ? theme.sun[0] : theme.sun[1];
        else if (d <= 10.4) color = theme.sun[2];
        else if (d <= 12.6 && (dx + dy) % 2 === 0) color = theme.sun[3];
        if (color) f(sunX + dx, sunY + dy, 1, 1, color);
      }
    }

    // Two soft clouds.
    const cloud = (cx, cy, scale) => {
      for (const [ox, oy, r] of [[-14, 2, 7], [-5, -3, 9], [6, -1, 8], [15, 3, 6]]) {
        for (let dy = -r; dy <= r; dy++) {
          const span = Math.floor(Math.sqrt(Math.max(0, r * r - dy * dy)) * scale);
          for (let dx = -span; dx <= span; dx++) f(cx + ox + dx, cy + oy + dy, 1, 1, dy > r * 0.35 ? '#cfe6ec' : '#f4fbfb');
        }
      }
    };
    if (theme.clouds) { cloud(Math.round(CW * 0.16), 30, 1.1); cloud(Math.round(CW * 0.52), 52, 0.85); }

    // Distant ridges: far one hazy, near one greener.
    const ridge = (x, base, amp, scale, seed) =>
      base + Math.round((Math.sin(x / scale + seed) * amp + Math.sin(x / (scale * 0.41) + seed * 3) * amp * 0.45) / 2) * 2;
    const FAR_BASE = Math.round(HORIZON * 0.72), NEAR_BASE = Math.round(HORIZON * 0.87);
    for (let x = 0; x < CW; x++) {
      const far = ridge(x, FAR_BASE, 7, 31, 1.4);
      f(x, far, 1, HORIZON - far, theme.far);
      f(x, far, 1, 2, theme.farLit);
    }
    if (theme.trees) {
      for (let i = 0; i < 17; i++) {
        const tx = 14 + i * Math.round(CW / 17) + ((i * 7) % 5);
        const top = ridge(tx, FAR_BASE, 7, 31, 1.4) - 7;
        f(tx, top, 1, 3, theme.tree);
        f(tx - 1, top + 3, 3, 2, theme.tree);
        f(tx - 2, top + 5, 5, 2, theme.treeLit);
      }
    }
    for (let x = 0; x < CW; x++) {
      const near = ridge(x, NEAR_BASE, 6, 47, 4.2);
      f(x, near, 1, HORIZON - near, theme.near);
      f(x, near, 1, 2, theme.nearLit);
    }

    // Meadow the bed sits in.
    f(0, HORIZON, CW, CH - HORIZON, theme.ground);
    f(0, HORIZON, CW, 5, theme.groundLit);
    for (let y = HORIZON; y < CH; y += 2) {
      for (let x = 0; x < CW; x += 3) {
        const n = hash(x, y);
        if (n > 0.82) f(x + (n * 3 | 0), y, 1, 2, theme.groundDark);
        else if (n < 0.16) f(x + (n * 9 | 0), y, 1, 1, theme.groundHi);
      }
    }
    if (theme.tufts) {
      for (let x = 2; x < CW; x += 9) {
        const y = HORIZON + 3 + Math.round(hash(x, 3) * 7);
        f(x, y, 1, 3, theme.groundDark);
        f(x + 1, y + 1, 1, 2, theme.groundHi);
        f(x + 2, y, 1, 3, theme.groundDark);
      }
    } else {
      // desert floor: scrub, pebbles and the odd larger stone
      const stone = (x, y, w, h) => {
        f(x, y + 1, w, h - 1, '#8d8278');
        f(x + 1, y, w - 2, 1, '#a99e92');
        f(x + 1, y + 1, Math.max(1, w - 4), 1, '#c6bbaf');
        f(x, y + h - 1, w, 1, '#6b6259');
      };
      for (let x = 4; x < CW; x += 9) {
        const y = HORIZON + 3 + Math.round(hash(x, 5) * 7);
        f(x, y, 2, 1, '#b39670');
        if (hash(x, 9) > 0.72) f(x + 2, y + 1, 2, 1, '#c9ad86');
      }
      for (const [sx, sy, sw, sh] of [[26, 6, 9, 5], [118, 3, 6, 4], [186, 8, 11, 6], [262, 4, 7, 4]]) {
        stone(sx, HORIZON + sy, sw, sh);
      }
      // low dry scrub along the horizon
      for (let x = 12; x < CW; x += 23) {
        const y = HORIZON + 2 + Math.round(hash(x, 17) * 5);
        f(x, y, 1, 3, '#9d8a5f'); f(x + 2, y - 1, 1, 4, '#b3a071'); f(x + 4, y, 1, 3, '#9d8a5f');
        f(x + 1, y + 2, 3, 1, '#8a7850');
      }
    }

    // The soil bed: a stepped mound with a lit top edge and a shaded front lip.
    const soil = wet ? theme.wet : theme.dry;
    const inset = x => {
      const e = Math.min(x - BED_L, BED_R - x);
      return e < 6 ? 3 : e < 13 ? 2 : e < 21 ? 1 : 0;
    };
    const topAt = x => (x < BED_L || x > BED_R ? -1 : BED_TOP + Math.round(Math.sin(x / 41) * 2) + inset(x) * 3);
    const bottomAt = x => BED_BOT - inset(x) * 3;

    for (let x = BED_L; x <= BED_R; x++) f(x, bottomAt(x) + 1, 1, 2, theme.cast);
    for (let x = 0; x < CW; x++) {
      const top = topAt(x);
      if (top < 0) continue;
      const bottom = bottomAt(x);
      for (let y = top; y <= bottom; y++) {
        const d = y - top;
        let color = soil.body;
        if (d === 0) color = soil.rim;
        else if (d <= 2) color = soil.edge;
        else if (d <= 6) color = soil.lit;
        else if (y > bottom - 5) color = soil.lip;
        else if (y > BED_TOP + (BED_BOT - BED_TOP) * 0.55) color = soil.deep;
        f(x, y, 1, 1, color);
      }
      // Grass tufts nosing over the back edge of the bed.
      if (theme.tufts && x % 7 === 3 && hash(x, 21) > 0.4) {
        f(x, top - 2, 1, 3, theme.groundDark);
        f(x + 1, top - 3, 1, 4, theme.groundHi);
      }
    }

    // Clods, crumbs and pebbles on a coarse lattice, so the soil reads as
    // turned earth rather than per-pixel static.
    for (let y = BED_TOP; y < BED_BOT; y += 2) {
      for (let x = BED_L; x < BED_R; x += 5) {
        const jx = x + Math.floor(hash(x, y) * 5);
        if (jx < BED_L || jx > BED_R - 3) continue;
        const top = topAt(jx), bottom = bottomAt(jx);
        if (top < 0 || y < top + 5 || y > bottom - 6) continue;
        const n = hash(jx * 2.3, y * 3.1);
        if (n > 0.93) { f(jx, y, 2, 1, soil.pebble); f(jx, y + 1, 2, 1, soil.spec); }
        else if (n > 0.74) f(jx, y, 3, 1, soil.lit);
        else if (n < 0.12) f(jx, y, 2, 1, soil.spec);
        else if (n < 0.22) f(jx + 1, y, 1, 1, soil.deep);
      }
    }

    if (biomeId === 'succulent') {
      const bedStone = (x, y, w, h) => {
        f(x, y + 1, w, h - 1, '#7d7268');
        f(x + 1, y, w - 2, 1, '#988d82');
        f(x + 1, y + 1, Math.max(1, w - 4), 1, '#b3a89c');
        f(x, y + h - 1, w, 1, '#5d554d');
      };
      for (const [sx, sy, sw, sh] of [[34, 0.30, 8, 5], [112, 0.62, 11, 6], [176, 0.24, 6, 4],
                                      [228, 0.72, 9, 5], [66, 0.84, 7, 4], [268, 0.44, 6, 4]]) {
        const y = Math.round(BED_TOP + (BED_BOT - BED_TOP) * sy);
        if (y + sh < BED_BOT - 2) bedStone(sx, y, sw, sh);
      }
      // pale dry patches, so the soil is not one flat tone
      for (let i = 0; i < 14; i++) {
        const x = 14 + Math.round(hash(i, 31) * (CW - 40));
        const y = Math.round(BED_TOP + 6 + hash(i, 37) * (BED_BOT - BED_TOP - 14));
        const w = 5 + Math.round(hash(i, 41) * 9);
        for (let dx = 0; dx < w; dx++) {
          if ((dx + i) % 3 === 0) continue;
          f(x + dx, y, 1, 1, '#a98a63');
          if (hash(x + dx, y) > 0.6) f(x + dx, y + 1, 1, 1, '#9a7c58');
        }
      }
    }

    bgCache[key] = layer;
    return layer;
  }

