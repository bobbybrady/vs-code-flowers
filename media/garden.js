  let critters = [];
  let nextSpawnAt = 0;
  const rand = (lo, hi) => lo + Math.random() * (hi - lo);

  function spawnCritter(now) {
    const defs = CREATURES[state.biome] || [];
    if (!defs.length) return;
    const def = defs[Math.floor(Math.random() * defs.length)];
    const lane = def.lane();
    const dir = Math.random() < 0.5 ? 1 : -1;
    critters.push({
      def, dir, born: now, phase: 'move',
      x: dir > 0 ? -18 : CW + 18,
      y: Math.round(rand(lane[0], lane[1])),
      until: now + rand(def.moveMs[0], def.moveMs[1])
    });
  }

  function updateCritters(now, dt) {
    const rate = WILDLIFE_RATE[state.wildlife || 'occasional'];
    if (!rate || reducedMotion || isPotted()) { critters.length = 0; return; }
    if (!nextSpawnAt) nextSpawnAt = now + rand(rate.gapMs[0], rate.gapMs[1]);
    if (now >= nextSpawnAt) {
      if (critters.length < rate.max) spawnCritter(now);
      nextSpawnAt = now + rand(rate.gapMs[0], rate.gapMs[1]);
    }
    critters = critters.filter(c => {
      if (c.phase === 'move') {
        c.x += c.dir * c.def.speed * dt;
        if (c.def.drift && Math.random() < 0.03) c.y += Math.random() < 0.5 ? -1 : 1;
        if (c.def.bob) c.y += Math.sin(now / 240 + c.born) * 0.5;
      }
      if (now >= c.until) {
        c.phase = c.phase === 'move' ? 'pause' : 'move';
        const range = c.phase === 'move' ? c.def.moveMs : c.def.pauseMs;
        c.until = now + rand(range[0], range[1]);
        if (c.phase === 'move' && Math.random() < c.def.turnChance) c.dir *= -1;
      }
      return c.x > -34 && c.x < CW + 34 && now - c.born < 120000;
    });
  }

  function drawCritters(now) {
    for (const c of critters) {
      const frames = c.def.frames;
      const key = c.phase === 'move' ? frames[Math.floor(now / c.def.frameMs) % frames.length] : frames[0];
      drawSprite(CREATURE_SPRITES[key], Math.round(c.x), Math.round(c.y), 0, 0, c.dir < 0);
    }
  }


