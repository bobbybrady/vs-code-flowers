  const spriteCache = new Map();
  function spriteImage(sprite, depth, flip) {
    let byVariant = spriteCache.get(sprite);
    if (!byVariant) { byVariant = []; spriteCache.set(sprite, byVariant); }
    const variant = depth * 2 + (flip ? 1 : 0);
    if (byVariant[variant]) return byVariant[variant];
    const palette = PALETTES[depth];
    const w = Math.max(...sprite.map(row => row.length));
    const layer = document.createElement('canvas');
    layer.width = w;
    layer.height = sprite.length;
    const g = layer.getContext('2d');
    g.imageSmoothingEnabled = false;
    sprite.forEach((row, y) => {
      const cells = flip ? [...row].reverse() : [...row];
      cells.forEach((cell, x) => {
        const color = palette[cell];
        if (!color) return;
        g.fillStyle = color;
        g.fillRect(x, y, 1, 1);
      });
    });
    byVariant[variant] = layer;
    return layer;
  }

